def _set_tokens(dark: bool, temperature: int) -> None:
    """Fill Palette and Ink for a mode and a temperature."""
    side = 0 if dark else 1
    for name, lightness in GREY_LIGHTNESS.items():
        value = grey(lightness[side], temperature / 100)
        if hasattr(Palette, name):
            setattr(Palette, name, value)
        else:
            setattr(Ink, name, rgb(value))
    for name, colors in MODE_COLORS.items():
        if hasattr(Palette, name):
            setattr(Palette, name, colors[side])
        else:
            setattr(Ink, name, rgb(colors[side]))
    Ink.DATA = rgb(Palette.TEXT)
    Ink.TRACE = Ink.GRID = rgb(Palette.TEXT_2)


_set_tokens(Scheme.DARK, Scheme.TEMPERATURE)


