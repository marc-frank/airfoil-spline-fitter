# The greys are generated from a lightness ramp and a temperature in OKLab,
# whose lightness is perceptual, so changing the temperature keeps every
# contrast. Lightness of each grey: (dark mode, light mode)
GREY_LIGHTNESS = {
    "CANVAS": (0.213, 0.995),
    "WINDOW": (0.236, 0.970),
    "PANEL": (0.268, 0.950),
    "FIELD": (0.309, 1.000),
    "FIELD_HOVER": (0.344, 0.965),
    "RULE": (0.360, 0.870),
    "RULE_STRONG": (0.434, 0.780),
    "TEXT": (0.982, 0.250),
    "TEXT_2": (0.807, 0.430),
    "TEXT_3": (0.686, 0.580),
    "SELECT": (0.405, 0.895),
    "SELECT_LINE": (0.609, 0.600),
    "CONSTRUCTION": (0.639, 0.620),
}
# Hue of warm and of cool greys, and their chroma per unit lightness at full
# temperature (the Claude Code greys are about +50)
WARM_HUE, COOL_HUE, TINT = 95.0, 255.0, 0.035
# Colors that change with the mode but not with the temperature: (dark, light)
MODE_COLORS = {
    "OK": ("#4FBF85", "#23905A"),
    "WARN": ("#F2B84B", "#B87A00"),
    "ERROR": ("#F0605D", "#D23B37"),
    "KNOTS": ("#F2C94C", "#C99A06"),
    "COMB_UPPER": ("#49B6E8", "#1E88C7"),
    "COMB_LOWER": ("#E5689A", "#CC3F78"),
}


def grey(lightness: float, temperature: float) -> str:
    """A grey of OKLab lightness 0-1, tinted warm (temperature > 0) or cool (< 0)."""
    hue = math.radians(WARM_HUE if temperature >= 0 else COOL_HUE)
    # Tinted in proportion to lightness, fading out toward white (paper stays white)
    chroma = abs(temperature) * TINT * lightness * min(1.0, (1 - lightness) * 20)
    a, b = chroma * math.cos(hue), chroma * math.sin(hue)
    l_ = (lightness + 0.3963377774 * a + 0.2158037573 * b) ** 3
    m_ = (lightness - 0.1055613458 * a - 0.0638541728 * b) ** 3
    s_ = (lightness - 0.0894841775 * a - 1.2914855480 * b) ** 3
    linear = (4.0767416621 * l_ - 3.3077115913 * m_ + 0.2309699292 * s_,
              -1.2684380046 * l_ + 2.6097574011 * m_ - 0.3413193965 * s_,
              -0.0041960863 * l_ - 0.7034186147 * m_ + 1.7076147010 * s_)

    def channel(c: float) -> int:
        c = min(max(c, 0.0), 1.0)
        c = 12.92 * c if c <= 0.0031308 else 1.055 * c ** (1 / 2.4) - 0.055
        return round(c * 255)

    return "#{:02X}{:02X}{:02X}".format(*(channel(c) for c in linear))


