def _palette() -> QPalette:
    """The Qt palette, so widgets drawn by the style itself match the tokens."""
    P = Palette
    pal = QPalette()
    roles = {
        QPalette.ColorRole.Window: P.WINDOW,
        QPalette.ColorRole.WindowText: P.TEXT,
        QPalette.ColorRole.Base: P.FIELD,
        QPalette.ColorRole.AlternateBase: P.PANEL,
        QPalette.ColorRole.Text: P.TEXT,
        QPalette.ColorRole.Button: P.FIELD,
        QPalette.ColorRole.ButtonText: P.TEXT,
        QPalette.ColorRole.Highlight: P.SELECT,
        QPalette.ColorRole.HighlightedText: P.TEXT,
        QPalette.ColorRole.ToolTipBase: P.FIELD,
        QPalette.ColorRole.ToolTipText: P.TEXT,
        QPalette.ColorRole.PlaceholderText: P.TEXT_3,
        QPalette.ColorRole.Link: P.TEXT_2,
        QPalette.ColorRole.Mid: P.RULE,
        QPalette.ColorRole.Midlight: P.RULE,
        QPalette.ColorRole.Dark: P.WINDOW,
        QPalette.ColorRole.Light: P.RULE_STRONG,
    }
    for role, color in roles.items():
        pal.setColor(role, QColor(color))
    for role in (QPalette.ColorRole.WindowText, QPalette.ColorRole.Text,
                 QPalette.ColorRole.ButtonText):
        pal.setColor(QPalette.ColorGroup.Disabled, role, QColor(P.TEXT_3))
    return pal


class _Notifier(QObject):
    changed = pyqtSignal()


# Emits ``changed`` after the theme changed. What the stylesheet does not
# style (plot items) connects to it and restyles itself.
theme_changed = _Notifier()


def _settings() -> QSettings:
    return QSettings("MSFra", "AirfoilSplineFitter")


def apply_theme(app: QApplication | None = None) -> None:
    """Style the application with the saved theme setting. Call before
    building any widget; safe to repeat."""
    app = app or QApplication.instance()
    if app is None or app.property("loftTheme"):
        return
    app.setProperty("loftTheme", True)
    settings = _settings()
    mode = settings.value("theme/mode", Scheme.MODE)
    Scheme.MODE = mode if mode in Scheme.MODES else "system"
    Scheme.TEMPERATURE = max(-100, min(100, settings.value("theme/temperature", 0, type=int)))
    Motion.SCROLL_MS = _motion_ms(settings.value("motion/scroll_ms", Motion.DEFAULT_SCROLL_MS, type=int))
    Motion.ZOOM_MS = _motion_ms(settings.value("motion/zoom_ms", Motion.DEFAULT_ZOOM_MS, type=int))
    app.setStyle("Fusion")
    # Numbers take the decimal point of the system locale, in fields,
    # readouts, messages and plots alike; no group separators
    locale = QLocale.system()
    locale.setNumberOptions(QLocale.NumberOption.OmitGroupSeparator)
    QLocale.setDefault(locale)
    set_decimal_point(locale.decimalPoint())
    font = app.font()
    font.setPointSize(Type.BASE_PT)
    app.setFont(font)
    app.setWindowIcon(app_icon())
    # Following the system: restyle when it switches between light and dark
    app.styleHints().colorSchemeChanged.connect(lambda _scheme: _restyle(app))
    _restyle(app)


def set_theme(mode: str | None = None, temperature: int | None = None) -> None:
    """Change and save the theme setting, and restyle the running app."""
    settings = _settings()
    if mode is not None:
        Scheme.MODE = mode
        settings.setValue("theme/mode", mode)
    if temperature is not None:
        Scheme.TEMPERATURE = temperature
        settings.setValue("theme/temperature", temperature)
    app = QApplication.instance()
    if app is not None and app.property("loftTheme"):
        _restyle(app)


def _motion_ms(ms: int) -> int:
    return max(0, min(Motion.MAX_MS, int(ms)))


def set_motion(scroll_ms: int | None = None, zoom_ms: int | None = None) -> None:
    """Change and save the glide durations; the next wheel step uses them."""
    settings = _settings()
    if scroll_ms is not None:
        Motion.SCROLL_MS = _motion_ms(scroll_ms)
        settings.setValue("motion/scroll_ms", Motion.SCROLL_MS)
    if zoom_ms is not None:
        Motion.ZOOM_MS = _motion_ms(zoom_ms)
        settings.setValue("motion/zoom_ms", Motion.ZOOM_MS)


def _restyle(app: QApplication) -> None:
    """Set the tokens for the current setting and restyle the app."""
    if Scheme.MODE == "system":
        dark = app.styleHints().colorScheme() != Qt.ColorScheme.Light
    else:
        dark = Scheme.MODE == "dark"
    Scheme.DARK = dark
    _set_tokens(dark, Scheme.TEMPERATURE)
    app.setPalette(_palette())
    app.setStyleSheet(_qss())
    pg.setConfigOptions(background=Palette.CANVAS, foreground=Palette.TEXT_2, antialias=True)
    theme_changed.changed.emit()


def app_icon() -> QIcon:
    """The application icon: the orange airfoil."""
    icon_ = QIcon()
    for name in ("app_icon.ico", "app_icon.png"):
        path = os.path.join(ASSETS, name)
        if os.path.exists(path):
            icon_.addFile(path)
    return icon_


def mono_font(point_size: float | None = None) -> QFont:
    """The monospace face for numbers."""
    font = QFont()
    font.setFamilies(Type.MONO_FAMILIES)
    font.setStyleHint(QFont.StyleHint.Monospace)
    if point_size:
        font.setPointSizeF(point_size)
    return font


