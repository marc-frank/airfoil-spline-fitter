class _DecadeAxis(pg.AxisItem):
    """An axis whose log scale labels only the decades (10^-6, 10^-5, ...),
    so the labels of the 2..9 ticks do not pile up below each decade.
    Without a decade in view, the other ticks keep their labels.

    The axis, its grid included, is cached as a pixmap: drawing it is most of
    a plot's repaint, and a new curve in the plot leaves it as it was."""

    def __init__(self, *args, **kwargs):
        super().__init__(*args, **kwargs)
        self.setCacheMode(QGraphicsItem.CacheMode.DeviceCoordinateCache)

    def updateAutoSIPrefix(self):
        # pyqtgraph rescales a labeled axis even with the prefix turned off
        if self.autoSIPrefix:
            super().updateAutoSIPrefix()
            return
        self.autoSIPrefixScale = 1.0
        self.labelUnitPrefix = ""
        self._updateLabel()

    def tickStrings(self, values, scale, spacing):
        strings = super().tickStrings(values, scale, spacing)
        return [s.replace(".", decimal_point()) for s in strings]

    def logTickStrings(self, values, scale, spacing):
        strings = super().logTickStrings(values, scale, spacing)
        low, high = sorted(self.range)
        if math.floor(high) < math.ceil(low):  # no decade in view
            return strings
        return [s if abs(v - round(v)) < 1e-9 else ""
                for v, s in zip(values, strings, strict=True)]


class FramedPlot(pg.PlotWidget):
    """A plot widget whose plot item fits inside the stylesheet's frame.

    pyqtgraph sizes the scene to the whole widget, so the 1 px border of the
    frame would cut the plot item's right and bottom edges off; this sizes it
    to the viewport inside the border, inset so that the 3 px outline the
    Export dialog draws centred on the item's edge shows whole on every side.
    """

    OUTLINE_INSET = 2   # half of the Export dialog's 3 px outline, rounded up

    def resizeEvent(self, ev):
        if self.closed:
            return
        if self.autoPixelRange:
            view = self.viewport().size()
            self.range = QRectF(0, 0, view.width(), view.height())
        pg.GraphicsView.setRange(self, self.range, padding=0, disableAutoPixel=False)
        if self.autoPixelRange and self.centralWidget is not None:
            i = self.OUTLINE_INSET
            self.centralWidget.setGeometry(self.range.adjusted(i, i, -i, -i))
        self.updateMatrix()


def style_plot(plot: pg.PlotWidget) -> None:
    """Drafting-film styling for a plot: grid, axes, labels and margins."""
    item = plot.getPlotItem()
    # An even margin above the plot area and right of it; the axis labels
    # on the left and bottom keep a small one
    m = Size.PLOT_MARGIN
    item.layout.setContentsMargins(Size.TIGHT, m, m, Size.TIGHT)
    if not isinstance(item.getAxis("left"), _DecadeAxis):
        item.setAxisItems({side: _DecadeAxis(side) for side in ("left", "bottom")})
    axis_pen = pg.mkPen(color=Ink.GRID, width=1)
    tick_font = QFont()
    tick_font.setPointSizeF(Type.BASE_PT - 1)
    for name in ("left", "bottom", "right", "top"):
        axis = item.getAxis(name)
        axis.setPen(axis_pen)
        axis.setTextPen(pg.mkPen(color=Palette.TEXT_2))
        axis.setTickFont(tick_font)
        # Values in the ticks, not a power of ten on the label
        axis.enableAutoSIPrefix(False)
        axis.label.setDefaultTextColor(QColor(Palette.TEXT_2))
        if axis.labelText:  # restyling: recolor the label
            axis.setLabel(axis.labelText, axis.labelUnits, axis.labelUnitPrefix,
                          **{**axis.labelStyle, "color": Palette.TEXT_2})
    plot.showGrid(x=True, y=True, alpha=Ink.GRID_ALPHA)
    plot.setBackground(Palette.CANVAS)


def label_plot(plot: pg.PlotWidget, side: str, text: str) -> None:
    """Set an axis label in the theme's label style."""
    plot.setLabel(side, text, color=Palette.TEXT_2, **{"font-size": f"{Type.BASE_PT}pt"})


def _qcolor(color, alpha: int = 255) -> QColor:
    """A token color (hex string or RGB tuple) as a QColor."""
    c = QColor(*color) if isinstance(color, tuple) else QColor(color)
    c.setAlpha(alpha)
    return c


def pen(color, width: float = Size.LINE_WIDTH, dashed: bool = False, alpha: int = 255):
    """A cosmetic pen of a token color."""
    style = Qt.PenStyle.DashLine if dashed else Qt.PenStyle.SolidLine
    return pg.mkPen(color=_qcolor(color, alpha), width=width, style=style)


def brush(color, alpha: int = 255):
    """A brush of a token color."""
    return pg.mkBrush(_qcolor(color, alpha))


