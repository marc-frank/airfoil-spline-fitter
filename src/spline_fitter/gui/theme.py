def _glyph(name: str, color: str | None = None, pad: int = 0) -> str:
    """Path of an SVG file of a glyph in a token color (written on first use),
    for the stylesheet.

    ``pad`` adds empty margin on the 12-unit grid, for places that stretch the
    image to fill a box (tree branches), so the glyph keeps its size.
    """
    color = color or Palette.TEXT_2
    folder = os.path.join(tempfile.gettempdir(), "spline_fitter_glyphs")
    path = os.path.join(folder, f"{name}_{color.lstrip('#').lower()}_{pad}.svg")
    if not os.path.exists(path):
        os.makedirs(folder, exist_ok=True)
        box = f"{-pad} {-pad} {12 + 2 * pad} {12 + 2 * pad}"
        svg = (f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="{box}">'
               f'<path d="{_GLYPHS[name]}" fill="none" stroke="{color}" stroke-width="1.4" '
               'stroke-linecap="round" stroke-linejoin="round"/></svg>')
        with open(path, "w", encoding="utf-8") as f:
            f.write(svg)
    return path.replace("\\", "/")


def _glyph_path(name: str) -> QPainterPath:
    """A glyph's path on the 12 x 12 grid (its data has only M and L commands)."""
    path = QPainterPath()
    words = _GLYPHS[name].replace("M", " M ").replace("L", " L ").split()
    for i in range(0, len(words), 3):
        point = QPointF(float(words[i + 1]), float(words[i + 2]))
        if words[i] == "M":
            path.moveTo(point)
        else:
            path.lineTo(point)
    return path


class _GlyphEngine(QIconEngine):
    """Paints a glyph in the current color of a token, so icons follow theme changes."""

    def __init__(self, name: str, role: str, checked_role: str | None = None):
        super().__init__()
        self._name, self._role, self._checked_role = name, role, checked_role or role

    def paint(self, painter: QPainter, rect: QRect, mode, state) -> None:
        if mode == QIcon.Mode.Disabled:
            color = Palette.TEXT_3
        elif state == QIcon.State.On:
            color = getattr(Palette, self._checked_role)
        else:
            color = getattr(Palette, self._role)
        side = min(rect.width(), rect.height())
        painter.save()
        painter.setRenderHint(QPainter.RenderHint.Antialiasing)
        painter.translate(rect.x() + (rect.width() - side) / 2,
                          rect.y() + (rect.height() - side) / 2)
        painter.scale(side / 12, side / 12)
        stroke = QPen(QColor(color), 1.4)
        stroke.setCapStyle(Qt.PenCapStyle.RoundCap)
        stroke.setJoinStyle(Qt.PenJoinStyle.RoundJoin)
        painter.setPen(stroke)
        painter.drawPath(_glyph_path(self._name))
        painter.restore()

    def pixmap(self, size: QSize, mode, state) -> QPixmap:
        pix = QPixmap(size)
        pix.fill(Qt.GlobalColor.transparent)
        painter = QPainter(pix)
        self.paint(painter, QRect(0, 0, size.width(), size.height()), mode, state)
        painter.end()
        return pix

    def clone(self) -> QIconEngine:
        return _GlyphEngine(self._name, self._role, self._checked_role)


def icon(name: str, role: str = "TEXT_2", checked_role: str | None = None) -> QIcon:
    """A glyph as an icon (chevron_down/up/right/left, check, dash, range, sort_up/down or filter) in the
    color of the Palette token named ``role`` (``checked_role`` on a checked
    button); it follows theme changes."""
    return QIcon(_GlyphEngine(name, role, checked_role))


def glyph_size() -> QSize:
    """The icon size for glyph icons on buttons."""
    return QSize(Size.GLYPH, Size.GLYPH)


